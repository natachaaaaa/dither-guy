def extract_palette(img, n: int = 8) -> list[tuple[int, int, int]]:
    """Main colours of an image (median cut refined by k-means), dark to light."""
    from PIL import Image
    small = img.convert("RGB")
    small.thumbnail((256, 256))
    q = small.quantize(colors=max(2, min(256, n)), method=Image.Quantize.MEDIANCUT, kmeans=4)
    raw = q.getpalette()[: 3 * n]
    cols = [tuple(raw[i:i + 3]) for i in range(0, len(raw), 3)]
    used = sorted(set(q.getdata()))
    cols = [cols[i] for i in used if i < len(cols)]
    return sorted(cols, key=lambda c: 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2])
